/**
 * Generates lib/seo/page-modified.generated.json — the real last-modified date
 * of every static page, taken from the last git commit that touched its source.
 *
 * WHY THIS EXISTS
 * The sitemap used to stamp `new Date()` on every static page, so all 81 page
 * URLs and all 54 help URLs reported a new <lastmod> on every revalidation —
 * once a minute — regardless of whether anything changed. Google ignores
 * lastmod when it proves unreliable, so an always-now value is worse than none.
 *
 * WHY THE OUTPUT IS COMMITTED
 * Vercel builds from a shallow clone, where `git log` cannot see the commit
 * that last touched a given file. So the map is generated here, committed, and
 * simply read at build time. Regenerate after changing pages:
 *
 *     pnpm sitemap:dates
 *
 * The script refuses to write from a shallow clone rather than overwriting good
 * dates with a single clone-time date, and always exits 0 so it can be wired
 * into a build without ever breaking one.
 */
import { execFileSync } from "node:child_process"
import { existsSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const OUT = join(ROOT, "lib", "seo", "page-modified.generated.json")

function git(args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim()
}

function bail(reason) {
  console.warn(`[sitemap:dates] skipped — ${reason}`)
  console.warn(`[sitemap:dates] existing ${OUT} left untouched.`)
  process.exit(0)
}

try {
  git(["rev-parse", "--is-inside-work-tree"])
} catch {
  bail("not a git repository")
}

if (git(["rev-parse", "--is-shallow-repository"]) === "true") {
  bail("shallow clone — per-file history is unavailable here")
}

// The registry is TypeScript, so read the route keys textually rather than
// pulling a TS toolchain into a build script.
const registry = join(ROOT, "lib", "seo", "registry.ts")
const source = await import("node:fs").then((fs) => fs.readFileSync(registry, "utf8"))
const paths = [...source.matchAll(/^\s{2}"(\/[^"]*)":\s*\{/gm)].map((m) => m[1])

if (paths.length === 0) bail("no route keys found in lib/seo/registry.ts")

/** Candidate source files for a route, most specific first. */
function filesFor(routePath) {
  const rel = routePath === "/" ? "" : routePath
  return [
    join("app", rel, "page.tsx"),
    join("app", rel, "page.ts"),
    join("app", rel, "page.mdx"),
  ].filter((f) => existsSync(join(ROOT, f)))
}

const dates = {}
let matched = 0
let missing = 0

for (const routePath of paths) {
  const files = filesFor(routePath)
  if (files.length === 0) {
    missing += 1
    continue
  }
  // Newest commit across the route's own files. Components shared between
  // pages are deliberately not followed: editing a shared button should not
  // re-date every page that renders it.
  let newest
  for (const file of files) {
    const iso = git(["log", "-1", "--format=%cI", "--", file])
    if (!iso) continue
    const time = new Date(iso).getTime()
    if (!Number.isNaN(time) && (newest === undefined || time > newest)) newest = time
  }
  if (newest === undefined) {
    missing += 1
    continue
  }
  dates[routePath] = new Date(newest).toISOString()
  matched += 1
}

// Deliberately no HEAD sha or generation timestamp in the output: prebuild
// rewrites this file on every build, and a commit-varying field would make it
// show up as modified every time even when no page date actually changed.
const payload = {
  _comment:
    "Generated by scripts/generate-page-dates.mjs — do not edit by hand. Run: pnpm sitemap:dates",
  pages: Object.fromEntries(Object.entries(dates).sort(([a], [b]) => a.localeCompare(b))),
}

writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`, "utf8")
console.log(`[sitemap:dates] wrote ${matched} page dates (${missing} without a source file)`)
