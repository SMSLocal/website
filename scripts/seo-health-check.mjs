/**
 * Technical SEO health check for the live site.
 *
 *     pnpm seo:check                  # checks https://www.smslocal.in
 *     pnpm seo:check http://localhost:3000
 *
 * Exits non-zero when a check fails, so it can gate a deploy or run on a
 * schedule. Everything here is verifiable from outside the app — it says
 * nothing about rankings or traffic, which only Search Console can answer.
 *
 * Checks:
 *   1. /sitemap.xml is a sitemap index and lists children.
 *   2. Every child sitemap parses and is a <urlset>.
 *   3. No duplicate URLs, all absolute HTTPS on the canonical host, all
 *      trailing-slashed to match trailingSlash: true.
 *   4. Every <lastmod> is a valid date and not in the future.
 *   5. lastmod is stable — two fetches must be byte-identical. This is the
 *      regression guard for the bug where every page reported `new Date()`
 *      on each revalidation.
 *   6. A sample of URLs returns 200, is not noindex, and self-canonicalises.
 *   7. robots.txt is served and points at the sitemap.
 */
const BASE = (process.argv[2] ?? "https://www.smslocal.in").replace(/\/$/, "")
const SAMPLE_SIZE = Number(process.env.SEO_CHECK_SAMPLE ?? 25)

const failures = []
const notes = []
const fail = (msg) => failures.push(msg)
const note = (msg) => notes.push(msg)

async function get(url) {
  const res = await fetch(url, { redirect: "manual" })
  return { status: res.status, body: await res.text(), headers: res.headers }
}

// Deliberately dependency-free: the sitemap XML is machine-generated by this
// repo and regular, so extracting elements by regex avoids adding a package to
// the production dependency tree purely for a check script.
const textOf = (xml, tag) =>
  [...xml.matchAll(new RegExp(`<${tag}>([^<]*)</${tag}>`, "g"))].map((m) => m[1].trim())

/** Split a <urlset> into <url> blocks so each loc stays paired with its lastmod. */
const urlBlocks = (xml) => [...xml.matchAll(/<url>([\s\S]*?)<\/url>/g)].map((m) => m[1])

const decode = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")

// ── 1. Index ────────────────────────────────────────────────────────────────
const index = await get(`${BASE}/sitemap.xml`)
if (index.status !== 200) fail(`/sitemap.xml returned ${index.status}`)

if (!/<sitemapindex[\s>]/.test(index.body)) fail("/sitemap.xml is not a <sitemapindex>")

const children = textOf(index.body, "loc").map(decode)
if (children.length === 0) fail("sitemap index lists no child sitemaps")
note(`index lists ${children.length} child sitemaps`)

// ── 2-4. Children ───────────────────────────────────────────────────────────
const seen = new Set()
const allUrls = []
let withLastmod = 0

for (const child of children) {
  const res = await get(child)
  if (res.status !== 200) {
    fail(`${child} returned ${res.status}`)
    continue
  }
  if (!/<urlset[\s>]/.test(res.body)) {
    fail(`${child} is not a <urlset>`)
    continue
  }
  const entries = urlBlocks(res.body)
  if (entries.length === 0) fail(`${child} contains no URLs`)

  for (const block of entries) {
    const loc = decode(textOf(block, "loc")[0] ?? "")
    const lastmod = textOf(block, "lastmod")[0]

    if (!loc) {
      fail(`${child} has a <url> with no <loc>`)
      continue
    }
    if (seen.has(loc)) fail(`duplicate URL across sitemaps: ${loc}`)
    seen.add(loc)
    allUrls.push(loc)

    if (!loc.startsWith(`${BASE}/`)) fail(`URL outside ${BASE}: ${loc}`)
    if (!loc.endsWith("/")) fail(`URL missing trailing slash: ${loc}`)

    if (lastmod !== undefined) {
      withLastmod += 1
      const when = new Date(lastmod)
      if (Number.isNaN(when.getTime())) fail(`invalid lastmod on ${loc}: ${lastmod}`)
      // A day of slack absorbs clock skew between here and the server.
      else if (when.getTime() > Date.now() + 86_400_000) {
        fail(`lastmod in the future on ${loc}: ${lastmod}`)
      }
    }
  }
  note(`${child.split("/").pop()}: ${entries.length} URLs`)
}
note(`${allUrls.length} URLs total, ${withLastmod} with <lastmod>`)

// ── 5. lastmod stability ────────────────────────────────────────────────────
// The regression this guards against produced a fresh timestamp per render, so
// a second fetch differs even with no deploy in between.
if (children.length > 0) {
  const target = children[0]
  const first = await get(target)
  const second = await get(target)
  if (first.body !== second.body) {
    const a = [...first.body.matchAll(/<lastmod>([^<]+)</g)].map((m) => m[1])
    const b = [...second.body.matchAll(/<lastmod>([^<]+)</g)].map((m) => m[1])
    const moved = a.filter((v, i) => v !== b[i]).length
    fail(
      `${target} changed between two consecutive fetches (${moved} lastmod values differ) — ` +
        `lastmod is being generated per request again`,
    )
  } else {
    note(`lastmod stable across consecutive fetches of ${target.split("/").pop()}`)
  }
}

// ── 6. Sample the pages themselves ──────────────────────────────────────────
const shuffled = [...allUrls].sort(() => Math.random() - 0.5).slice(0, SAMPLE_SIZE)
let sampled = 0
for (const url of shuffled) {
  const res = await get(url)
  sampled += 1
  if (res.status !== 200) {
    fail(`${url} returned ${res.status}`)
    continue
  }
  const robots = res.body.match(/<meta[^>]+name=["']robots["'][^>]*>/i)?.[0] ?? ""
  if (/noindex/i.test(robots)) fail(`in sitemap but noindex: ${url}`)

  const canonical = res.body.match(/<link[^>]+rel=["']canonical["'][^>]+href=["']([^"']+)/i)?.[1]
  if (canonical && canonical !== url) fail(`canonical mismatch: ${url} -> ${canonical}`)
}
note(`sampled ${sampled} pages for status, noindex and canonical`)

// ── 7. robots.txt ───────────────────────────────────────────────────────────
const robots = await get(`${BASE}/robots.txt`)
if (robots.status !== 200) fail(`/robots.txt returned ${robots.status}`)
else if (!/^sitemap:/im.test(robots.body)) fail("/robots.txt has no Sitemap: line")
else note("robots.txt served and references the sitemap")

// ── Report ──────────────────────────────────────────────────────────────────
console.log(`\nSEO health check — ${BASE}\n`)
for (const n of notes) console.log(`  ok    ${n}`)
if (failures.length > 0) {
  console.log("")
  for (const f of failures) console.log(`  FAIL  ${f}`)
  console.log(`\n${failures.length} problem(s) found.\n`)
  // exitCode rather than process.exit(): forcing exit while keep-alive sockets
  // are still open trips a libuv assertion on Windows.
  process.exitCode = 1
}
console.log(`\nAll checks passed.\n`)
